const lookup = (dict: Record<string, string>, text: string) => dict[text.trim().toLowerCase()];

/** Units and counts inside values: "11.4-inch", "6 units", "13 speakers", "10-color", "Front row: 2" … */
const patterns: [RegExp, (m: RegExpMatchArray) => string][] = [
  [/^(\d+(?:\.\d+)?)-inch$/i, (m) => `${m[1].replace(".", ",")}"`],
  [/^(\d+) units?$/i, (m) => `${m[1]} бр.`],
  [/^(\d+) speakers?$/i, (m) => `${m[1]} бр.`],
  [/^(\d+)-colou?r$/i, (m) => `${m[1]} цвята`],
  [/^front row: (\d+)$/i, (m) => `Отпред: ${m[1]}`],
  [/^rear row: (\d+)$/i, (m) => `Отзад: ${m[1]}`],
  [/^(\d+)-speed automatic with manual shift mode$/i, (m) => `${m[1]}-степенна автоматична с ръчен режим`],
  [/^(\d+)-speed automatic$/i, (m) => `${m[1]}-степенна автоматична`],
  [/^(\d+)-speed manual$/i, (m) => `${m[1]}-степенна ръчна`],
  [/^(\d+)-speed dual-clutch$/i, (m) => `${m[1]}-степенна двусъединителна (DCT)`],
  [/^china vi(?:a|b)?$/i, () => "China VI (≈ Евро 6)"],
  [/^china v$/i, () => "China V (≈ Евро 5)"],
  [/^monocular x(\d+)$/i, (m) => `Моно камера × ${m[1]}`],
  [/^(\d+) years? or ([\d,]+) (?:km|kilometers)$/i, (m) => `${m[1]} г. или ${m[2]} км`],
];

function translateValuePart(part: string): string {
  const exact = lookup(values, part) ?? lookup(names, part);
  if (exact) return exact;
  for (const [re, fmt] of patterns) {
    const m = part.trim().match(re);
    if (m) return fmt(m);
  }
  return part;
}

/** Bulgarian name of a group ("Seat Features" -> "Седалки"); the original when unknown. */
export function specGroupName(name: string): string {
  return lookup(groups, name) ?? name;
}

/** Bulgarian name of a row ("Wheelbase (mm)" -> "Междуосие (мм)"); the original when unknown. */
export function specItemName(name: string): string {
  return lookup(names, name) ?? name;
}

/** Bulgarian value; a list "Heating, Ventilation" part by part; "" (fitted, no details) stays "". */
export function specValue(value: string): string {
  if (!value) return "";
  const whole = translateValuePart(value);
  if (whole !== value) return whole;
  return value
    .split(", ")
    .map(translateValuePart)
    .join(", ");
}

/** The sheet ready for the car page: Bulgarian names and values, empty groups left out. */
export function translatedSheet(sheet: SpecGroup[] | undefined) {
  return (sheet ?? [])
    .filter((g) => g.items.length > 0)
    .map((g) => ({
      name: specGroupName(g.name),
      items: g.items.map((i) => ({ name: specItemName(i.name), value: specValue(i.value) })),
    }));
}
